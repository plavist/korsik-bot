def persona_prompt(emp: dict | None) -> str:
    if emp and emp.get("form") == "vy":
        address = "сотрудник выбрал общение на «ВЫ» — пиши на «вы» (вежливо, но тепло, без фамильярности)."
    else:
        address = "по умолчанию на «ТЫ» (дружелюбно, как с коллегой); если человек сам пишет на «вы» и просит так общаться — переходи на «вы»."
    if emp:
        site = scenario.SITE_TITLES.get(emp["site"], emp["site"])
        context = (f"зовут {first_name(emp)}; площадка: {site}; сейчас этап: {stage(emp)}; "
                   f"дата выхода: {emp['hire_date']}; испытательный срок 3 месяца.")
    else:
        context = "человек не привязан к сценарию адаптации (имя и этап неизвестны); обращайся на «ты» без имени."
    return PERSONA.replace("{address_rule}", address).replace("{context}", context).replace("{name}", first_name(emp) if emp else "друг")
