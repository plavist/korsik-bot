STAGE_NAMES = [  # (порог в днях от выхода, описание этапа)
    (-1, "до выхода на работу"), (0, "первый рабочий день"), (2, "первые дни работы"), (13, "первые две недели"),
    (30, "первый месяц работы"), (60, "второй месяц работы"), (10_000, "финишная прямая испытательного срока"),
]


def first_name(emp: dict | None) -> str:
    return (emp["name"].split()[0] if emp and emp.get("name") else "друг")


def stage(emp: dict, today: date | None = None) -> str:
    days = ((today or date.today()) - date.fromisoformat(emp["hire_date"])).days
    return next(name for limit, name in STAGE_NAMES if days <= limit)


FORMAL_PROMPT = """Перепиши сообщение чат-бота Корсика, обращаясь к человеку на «вы» (вежливая форма, местоимение «вы» с маленькой
буквы). Строго сохрани: смысл, абзацы, переносы строк, эмодзи, нумерацию, ссылки, имена, обращение по имени.
Бот говорит о себе в мужском роде. Тон остаётся тёплым и дружелюбным. «Вы/Вам» с большой буквы только в начале
предложения или строки (включая строку после номера: «1. Вам понятны…»), иначе — с маленькой. Ничего не добавляй и не убирай.
Верни только переписанный текст без комментариев."""


_YOU = r"(вы|вам|вами|вас|ваш\w*)"
_AFTER_NUMBER = re.compile(r"(?m)^(\s*\d+[.)]\s*)" + _YOU + r"\b")
_LINE_START = re.compile(r"(?m)^" + _YOU + r"\b")
_SENTENCE_START = re.compile(r"([.!?…]\s+)" + _YOU + r"\b")


def fix_formal_case(text: str) -> str:
    """«Вы/Вам» в начале строки, после номера пункта («1. Вам понятны…») и после точки — с большой буквы."""
    cap = lambda m: m.group(1) + m.group(2)[0].upper() + m.group(2)[1:]  # noqa: E731
    text = _AFTER_NUMBER.sub(cap, text)
    text = _SENTENCE_START.sub(cap, text)
    return _LINE_START.sub(lambda m: m.group(1)[0].upper() + m.group(1)[1:], text)


_FEM_ADJ = {"рада": "рад", "готова": "готов", "уверена": "уверен", "благодарна": "благодарен", "счастлива": "счастлив", "довольна": "доволен"}
_FEM_IRREGULAR = {"нашла": "нашёл", "пришла": "пришёл", "ушла": "ушёл", "дошла": "дошёл", "смогла": "смог", "помогла": "помог",
                  "могла": "мог", "зашла": "зашёл", "прошла": "прошёл", "отошла": "отошёл"}
_FILLER = r"(?:(?:уже|ещё|еще|не|бы|сразу|обязательно|тоже|только|сейчас|лично|вам|тебе|ему|ей|им|вас|тебя)\s+){0,3}"
_FEM_VERB = re.compile(r"\b([Яя]\s+" + _FILLER + r")(\w+?л(?:а|ась))\b")
_FEM_ADJ_RE = re.compile(r"\b(" + "|".join(_FEM_ADJ) + r")\b", re.I)


_USER_GENDERED = re.compile(r"(?i)\bспасибо,?\s+что\s+(?:ты\s+|вы\s+)?(?:рассказал|поделил|написал|обратил|доверил|открыл|признал)\w*(?:\(а\))?")


def fix_gender(text: str) -> str:
    """Страховка: бот говорит о себе в мужском роде («я передал») и не угадывает пол собеседника
    («Спасибо, что рассказал/-ла» → «Спасибо за откровенность»)."""
    text = _USER_GENDERED.sub(lambda m: "Спасибо за откровенность" if m.group(0)[0].isupper() else "спасибо за откровенность", text)
    def verb(m):
        w = m.group(2)
        low = w.lower()
        masc = _FEM_IRREGULAR.get(low) or (w[:-4] + "лся" if low.endswith("лась") else w[:-1])
        return m.group(1) + (masc[0].upper() + masc[1:] if w[0].isupper() else masc)
    text = _FEM_VERB.sub(verb, text)
    return _FEM_ADJ_RE.sub(lambda m: _FEM_ADJ[m.group(0).lower()] if m.group(0).islower() else _FEM_ADJ[m.group(0).lower()].capitalize(), text)


async def to_formal(text: str) -> str:
    key = "vy:" + hashlib.sha1(text.encode(), usedforsecurity=False).hexdigest()
    cached = db.get_rewrite(key)
    if cached:
        return fix_formal_case(cached)
    try:
        msg = await llm.chat([{"role": "system", "content": FORMAL_PROMPT}, {"role": "user", "content": text}],
                             temperature=0, max_tokens=3000)
        out = (msg.get("content") or "").strip()
    except Exception:  # noqa: BLE001 — не получилось переписать: отправляем оригинал
        return text
    if not out or not (0.5 * len(text) <= len(out) <= 2 * len(text) + 40):
        return text
    out = fix_formal_case(out)
    db.set_rewrite(key, out)
    return out


async def personalize(text: str, emp: dict | None) -> str:
    text = text.replace("{name}", first_name(emp))
    if emp and emp.get("form") == "vy":
        text = await to_formal(text)
    return text


async def personalize_many(texts: list[str], emp: dict | None) -> list[str]:
    return list(await asyncio.gather(*(personalize(t, emp) for t in texts)))


