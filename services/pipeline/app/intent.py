"""Интент «обратиться к HR»: по смыслу вопроса понимаем, что сотруднику, скорее всего, нужен человек, а не справка из базы.
Страховка к решению модели: вопрос сразу передаётся HR (бесшовная эскалация), бот при этом отвечает как обычно."""
import re

# (причина для HR, шаблон). Основы слов без окончаний; регистр не важен (ё/е указаны в шаблонах).
RULES = [
    ("конфликт или давление на работе", r"конфликт|травл|буллинг|притесн|обижа|оскорб|унижа|издева|давлен|кричит на|орёт на|орет на|угрожа|домогат|дискримин"),
    ("вопрос об оплате или условиях труда", r"зарплат|оклад|аванс|премию|премии|не заплат|не выплат|задерж\w* (?:зп|зарплат|выплат)|переработк|сверхурочн|незаконн|нарушени\w* (?:тк|трудов|закон)"),
    ("увольнение или уход из компании", r"увол|хочу уйти|хочу уходить|собираюсь уйти|написать заявление|не хочу (?:тут|здесь|больше) работ|расторг"),
    ("жалоба или проблема с руководителем/коллегами", r"жалоб|пожаловать|не нрав\w* (?:руковод|начальник|коллег)|плохо относ|проблем\w* с (?:руковод|начальник|коллег|наставник)|несправедлив"),
    ("здоровье или безопасность", r"травм|несчастн\w* случа|плохо себя чувств|заболел|больничн\w* не|небезопасн|опасн\w* на (?:рабоч|производ)|выгоран|депресс|тревог|паническ"),
    ("просьба о живом человеке", r"живо\w* человек|живым|поговорить с (?:кем|человек|hr|эйчар|хр)|связать\w* с (?:hr|эйчар|хр|человек|сотрудник\w* подбор)|позови\w* (?:hr|эйчар|хр|человек)|нужен (?:hr|эйчар|хр|человек)|хочу (?:к|в) (?:hr|эйчар|хр)|не помогает|ты не понима"),
]
_COMPILED = [(reason, re.compile(rx)) for reason, rx in RULES]


def detect(text: str) -> str | None:
    """Причина для HR, если вопрос похож на эскалацию, иначе None."""
    t = (text or "").lower()
    for reason, rx in _COMPILED:
        if rx.search(t):
            return reason
    return None
