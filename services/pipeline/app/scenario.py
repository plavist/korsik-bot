# ---------- конструкторы ----------
def M(text, sites=None, office=None, asset=None, fallback=None, cond=None, req=False, hr=None):
    """asset — метка вложения (картинка/PDF), которое HR загружает в библиотеку; req=True — без вложения сообщение бессмысленно:
    шлём fallback, а если его нет — пропускаем. Без req текст уходит всегда. image — выбранный файл из библиотеки."""
    return {"t": "msg", "text": text, "sites": sites, "office": office, "asset": asset, "fallback": fallback, "cond": cond, "req": req, "hr": hr,
            "image": None}


def D(anchor, days=0, months=0, workdays=False, time="09:00"):
    """Срок отправки этапа: от даты выхода ("hire") или конца испытательного срока ("end") + месяцы + дни (рабочие/календарные), время."""
    return {"anchor": anchor, "months": months, "days": days, "workdays": workdays, "time": time}


def KB(query, fallback, sites=None):
    return {"t": "kb", "query": query, "fallback": fallback, "sites": sites, "office": None, "cond": None}


def O(label, value=None, then=None, hr=False, escalate=None, follow=None, contact=False):
    """Вариант ответа. then — текст/элементы после ответа; hr — кнопки «Опции для сотрудника» из ТЗ: True — «Передать HR через
    Корсика» + «Связаться с рекрутером», "contact" — только «Связаться с рекрутером»;
    escalate — создать обращение для HR (красный флаг); follow — открытый вопрос после ответа;
    contact — кнопка «готов озвучить причину в личной коммуникации с рекрутером»."""
    if isinstance(then, str):
        then = [M(then)]
    return {"label": label, "value": value or label, "then": then or [], "hr": hr, "escalate": escalate,
            "follow": follow, "contact": contact}


