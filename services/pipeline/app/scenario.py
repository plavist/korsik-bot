def validate_due(spec) -> dict | None:
    """None — по событию (привязка к боту). Иначе нормализованный словарь; ValueError — если некорректен."""
    if spec is None:
        return None
    try:
        out = {"anchor": spec.get("anchor"), "months": int(spec.get("months") or 0), "days": int(spec.get("days") or 0),
               "workdays": bool(spec.get("workdays")), "time": str(spec.get("time") or "")}
        h, m = out["time"].split(":")
        assert 0 <= int(h) < 24 and 0 <= int(m) < 60 and len(h) == 2 and len(m) == 2
        assert out["anchor"] in ("hire", "end") and -400 <= out["days"] <= 400 and -24 <= out["months"] <= 24
    except (AttributeError, TypeError, ValueError, AssertionError):
        raise ValueError("срок: точка отсчёта (выход / конец испытательного срока), смещение и время ЧЧ:ММ") from None
    if out["workdays"] and (out["days"] < 0 or out["months"]):
        raise ValueError("рабочие дни считаются только вперёд и без месяцев")
    return out


def due_datetime(spec: dict, d: dict) -> datetime:
    base = d[spec["anchor"]]
    if spec["months"]:
        base = add_months(base, spec["months"])
    base = add_workdays(base, spec["days"]) if spec["workdays"] else base + timedelta(days=spec["days"])
    return at(base, spec["time"])


def describe_due(spec: dict | None) -> str:
    if not spec:
        return "При привязке к боту (рекрутер даёт QR/код)"
    n, mo, t = spec["days"], spec["months"], spec["time"]
    who = "выхода" if spec["anchor"] == "hire" else "конца испытательного срока"
    if not n and not mo:
        return f"В день выхода, {t}" if spec["anchor"] == "hire" else f"В последний день испытательного срока, {t}"
    parts = []
    if mo:
        parts.append(f"{mo} мес.")
    if n:
        parts.append(f"{abs(n)} {'раб. дн.' if spec['workdays'] else 'дн.'}")
    return f"{'За' if n < 0 else 'Через'} {' '.join(parts)} {'до' if n < 0 else 'после'} {who}, {t}"


def due_at(step: dict, emp: dict):
    return due_datetime(step["due"], dates(emp)) if step.get("due") else None


def applies(item_or_step: dict, emp: dict) -> bool:
    sites = item_or_step.get("sites")
    if sites and emp["site"] not in sites:
        return False
    office = item_or_step.get("office")
    return office is None or office == emp["is_office"]


# ---------- загрузка и сохранение ----------
def load_sites() -> None:
    raw = db.get_setting("sites")
    sites = json.loads(raw) if raw else copy.deepcopy(DEFAULT_SITES)
    ALL_SITES[:] = [x["code"] for x in sites]
    SITE_TITLES.clear()
    SITE_TITLES.update({x["code"]: x["title"] for x in sites})
    SITE_OFFICE.clear()
    SITE_OFFICE.update({x["code"]: bool(x.get("office", True)) for x in sites})


def site_list() -> list[dict]:
    return [{"code": c, "title": SITE_TITLES[c], "office": SITE_OFFICE[c]} for c in ALL_SITES]


def save_sites(sites: list[dict]) -> None:
    db.set_setting("sites", json.dumps(sites, ensure_ascii=False))
    load_sites()


def _with_legacy_overrides(steps: list) -> list:
    """Тексты и картинки, правленные до появления редактора сценария (настройки text:/image:), переносим в сам сценарий."""
    for st in steps:
        for idx, it in enumerate(st["items"]):
            txt = db.get_setting(f"text:{st['id']}:{idx}")
            if txt and "text" in it:
                it["text"] = txt
            img = db.get_setting(f"image:{st['id']}:{idx}")
            if img and img != "none" and it["t"] == "msg":
                it["image"] = img
    return steps


def reset() -> None:
    """Перечитывает площадки и сценарий из настроек (нет сохранённого — берём исходный)."""
    load_sites()
    raw = db.get_setting("scenario:doc")
    steps = json.loads(raw) if raw else _with_legacy_overrides(copy.deepcopy(_DEFAULT_STEPS))
    STEPS[:] = steps
    STEP_BY_ID.clear()
    STEP_BY_ID.update({s_["id"]: s_ for s_ in STEPS})


def save(steps: list) -> None:
    db.set_setting("scenario:doc", json.dumps(steps, ensure_ascii=False))
    reset()


def default_steps() -> list:
    return copy.deepcopy(_DEFAULT_STEPS)
